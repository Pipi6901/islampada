import SwiftUI

/// Раскладка под экраны, которые шире и ниже обычного iPhone.
///
/// Макеты рисовались на 393×852, и почти все экраны были свёрстаны так, чтобы
/// ровно лечь в эту высоту, без прокрутки. iPhone Duo принёс два экрана других
/// пропорций: внешний — примерно 466×678 точек, внутренний — 669×951, а лёжа
/// 951×669. Внутренний к тому же не соблюдает блокировку портретной
/// ориентации. На внешнем по высоте на ~170 точек меньше, чем в макете, и всё,
/// что не прокручивается, уезжало бы за край — у пейволла вместе с кнопкой
/// покупки. На внутреннем по ширине в два с половиной раза больше, и строки
/// стиха растягивались бы во всю ширину.
enum ScreenLayout {
    /// Шире колонку не растягиваем: длинная строка стиха хуже читается, а
    /// карточки и кнопки на 950 точек выглядят пустыми. На обычных iPhone до
    /// этого предела далеко — там колонка ничего не меняет.
    static let readableWidth: CGFloat = 560
}

extension View {
    /// Колонка не шире `ScreenLayout.readableWidth`, по центру доступного места.
    ///
    /// Фон экрана вешается снаружи колонки, а не внутри: он должен по-прежнему
    /// занимать весь экран.
    func readableColumn() -> some View {
        frame(maxWidth: ScreenLayout.readableWidth)
            .frame(maxWidth: .infinity)
    }

    /// Экран без прокрутки, который начинает прокручиваться, только если не
    /// влез по высоте.
    ///
    /// Помещается — показывается ровно как раньше: распорки внутри растягиваются
    /// на всю высоту, и вёрстка совпадает с макетом. Не помещается — тот же
    /// экран уходит в прокрутку с распорками минимальной длины, и до кнопки
    /// внизу можно долистать. Прокрутка всегда, а не по необходимости, сжимала
    /// бы распорки и на обычных iPhone, где места хватает.
    ///
    /// Внутри не должно быть своей вертикальной прокрутки: вложенная в
    /// прокрутку, она получила бы бесконечную высоту.
    func fitOrScroll() -> some View {
        modifier(FitOrScroll())
    }
}

private struct FitOrScroll: ViewModifier {
    func body(content: Content) -> some View {
        // Выбирает первый вариант, чья естественная высота влезает в
        // предложенную. Естественная высота — с распорками минимальной длины,
        // то есть ровно «поместится ли содержимое вообще».
        ViewThatFits(in: .vertical) {
            content

            ScrollView {
                content
            }
            .scrollBounceBehavior(.basedOnSize)
            .scrollIndicators(.hidden)
        }
    }
}
