import Foundation

/// Разрешение на отслеживание (ATT) для рекламной атрибуции.
///
/// Окно спрашивает онбординг, а Meta SDK живёт в приложении: пакет линкует
/// расширение виджета, и рекламный SDK уехал бы туда следом. Поэтому
/// приложение ставит сюда, что делать, а онбординг только зовёт.
///
/// Спрашивают до пейволла: тогда начатый триал уходит в Meta уже с ответом,
/// и кампания учится на нём. Спросить после — значит отдать самое ценное
/// событие без привязки к рекламе.
@MainActor
public enum AdTracking {
    /// Показать системное окно и, получив ответ, поднять рекламный SDK.
    /// `nil` — спрашивать нечего: система уже знает ответ, или это тесты и
    /// предпросмотры. Тогда шага в онбординге нет.
    public static var prompt: (() async -> Void)?
}

/// Токен Firebase Messaging — для пробной рассылки из консоли на свой
/// телефон («Send test message»). Ставит приложение: пакет Firebase не знает.
///
/// Нет токена — возвращается причина, а не пустота: без неё долгое нажатие
/// молча ничего не делало, и было не понять, сломана кнопка или пуши.
@MainActor
public enum PushToken {
    public static var fetch: (() async -> Result<String, PushTokenError>)?
}

public struct PushTokenError: Error, Sendable {
    public let message: String

    public init(_ message: String) {
        self.message = message
    }
}
