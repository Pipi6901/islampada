import Foundation
import Observation

/// Пауза перед лентой: состояние одного показа.
///
/// КАК ЭТО РАБОТАЕТ. Человек заводит в «Командах» автоматизацию «когда открыто
/// приложение» и добавляет в неё одно наше действие «Пауза со стихом», указав в
/// нём ту же соцсеть. Тапнул соцсеть — открывается Lampada со стихом; нажал
/// «Продолжить» — Lampada сама открывает соцсеть обратно по её адресу.
///
/// ПОЧЕМУ ДЕЙСТВИЕ ОДНО, А НЕ ДВА. Раньше вторым действием стояло системное
/// «Открыть приложение», а наше намерение висело и не возвращалось, пока
/// человек не нажмёт кнопку, — чтобы возврат случился после паузы. Так делать
/// нельзя: «Команды» убивают действие, которое не уложилось в отведённое время
/// (на практике порядка пятнадцати секунд), и всё разваливалось разом —
/// «Сбой автоматизации», возврат не срабатывал, потому что до второго действия
/// дело не доходило. Теперь намерение возвращается сразу, а разговор с
/// человеком идёт уже внутри приложения. Так же устроен one sec.
///
/// ПРО ОКНО ТИШИНЫ И ОТСКОК. Условно не поднимать приложение из действия
/// нельзя: `openAppWhenRun` статическое, а поддерживаемой альтернативы у App
/// Intents нет. Поэтому в окне тишины Lampada всё равно оказывается на экране —
/// и если ничего не показать, человек видит просто наше приложение без стиха.
/// Так и было: закрыл соцсеть, открыл снова — и попал в Lampada с пустыми
/// руками. Теперь в этом случае приложение сразу отправляет его обратно по
/// адресу соцсети: мгновение Lampada, и он там, откуда пришёл.
///
/// Отскок ограничен одним разом за короткий промежуток. Если на каком-то iOS
/// программное открытие соцсети всё же поднимает автоматизацию, без ограничения
/// получился бы пинг-понг между двумя приложениями до конца окна.
///
@Observable
@MainActor
public final class PauseSession {
    public static let shared = PauseSession()

    /// Показывать ли экран паузы прямо сейчас.
    public private(set) var isShowing = false

    /// Куда вернуться по «Продолжить». Пусто — возвращаться некуда: соцсети нет
    /// в нашем списке или автоматизация собрана по старой схеме, без параметра.
    public private(set) var returnURL: URL?

    /// Сколько секунд после пройденной паузы автоматизация не показывает её
    /// снова. Окно должно перекрывать возврат в соцсеть и первые секунды в ней:
    /// иначе человек, случайно свернувший и открывший приложение снова, получит
    /// стих второй раз подряд.
    public static let grace: TimeInterval = 10

    /// Промежуток, в котором второй отскок подряд не делается.
    public static let bounceCooldown: TimeInterval = 3

    /// Куда отправить человека сразу, без показа: пауза только что пройдена, а
    /// приложение всё равно поднялось. Читает и гасит `consumeBounce`.
    public private(set) var bounceURL: URL?
    private var lastBounce: Date?

    private let store: UserDefaults
    private let key = "pause.lastPassed"

    /// Хранилище — общая группа, та же, что у настроек.
    ///
    /// С `openAppWhenRun` действие выполняется в процессе приложения, и личных
    /// `.standard` хватило бы. Но отметку о пройденной паузе однажды захочет
    /// читать и расширение — виджет или кнопка в Пункте управления, — а у них
    /// свой контейнер. Держать её сразу в группе дешевле, чем потом искать,
    /// почему из расширения окно тишины не видно.
    init(store: UserDefaults? = nil) {
        self.store = store ?? UserDefaults(suiteName: AppSettings.appGroup) ?? .standard
    }

    /// Вызывается намерением. Возвращается немедленно: ждать человека внутри
    /// действия «Команд» нельзя, его убьют по таймауту.
    public func begin(returnTo url: URL? = nil) {
        guard !isShowing else { return }
        if isWithinGrace {
            // Показывать нечего, а приложение уже открыто. Вернуть человека
            // туда, откуда он пришёл, — но не чаще одного раза подряд.
            let recently = lastBounce.map { Date.now.timeIntervalSince($0) < PauseSession.bounceCooldown } ?? false
            if let url, !recently { bounceURL = url }
            return
        }
        returnURL = url
        isShowing = true
    }

    /// Забрать адрес для отскока. Зовётся из интерфейса, когда сцена уже
    /// активна: открывать адрес раньше бессмысленно, система его проглотит.
    public func consumeBounce() -> URL? {
        guard let url = bounceURL else { return nil }
        bounceURL = nil
        lastBounce = .now
        return url
    }

    /// Пауза пройдена. Возвращает адрес соцсети, если возвращаться есть куда.
    ///
    /// Зовётся и по кнопке «Продолжить», и когда человек просто свернул
    /// приложение: стих он в обоих случаях увидел, а не засчитать уход — значит
    /// встретить его паузой снова на том же самом открытии соцсети.
    @discardableResult
    public func finish() -> URL? {
        guard isShowing else { return nil }
        isShowing = false
        store.set(Date.now.timeIntervalSince1970, forKey: key)
        let url = returnURL
        returnURL = nil
        return url
    }

    /// Прошла ли пауза совсем недавно.
    public var isWithinGrace: Bool {
        let last = store.double(forKey: key)
        guard last > 0 else { return false }
        return Date.now.timeIntervalSince1970 - last < PauseSession.grace
    }

    /// Для тестов: забыть, что пауза проходилась.
    func forget() {
        store.removeObject(forKey: key)
    }
}
