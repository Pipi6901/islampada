def parse(token):
    """'2:155-157' -> (2, 155, 157); '13:28' -> (13, 28, 28)."""
    sura, rest = token.split(":")
    if "-" in rest:
        a, b = rest.split("-")
    else:
        a = b = rest
    return int(sura), int(a), int(b)


def passages():
    """Список (тема, сура, с, по) в порядке состояний и порядке внутри состояния."""
    out = []
    taken = set()
    for theme, line in THEMES.items():
        for token in line.split():
            s, a, b = parse(token)
            assert b >= a, token
            for ayah in range(a, b + 1):
                assert (s, ayah) not in taken, f"аят {s}:{ayah} встречается дважды ({token})"
                taken.add((s, ayah))
            out.append((theme, s, a, b))
    return out


if __name__ == "__main__":
    p = passages()
    print(len(p), "отрывков,", len({t for t, *_ in p}), "состояний")
    for theme in THEMES:
        print(theme, sum(1 for t, *_ in p if t == theme))
